package Basic;

public class Main_01 {                          //Every line of code that runs in Java must be inside a class
    public static void main(String[] args){ //Any code placed inside the main() method will be executed.

        System.out.print("Hi Buddy! "); //we can use the print() method to print a line of text to the screen:
        System.out.println("Just Believe Yourself." );
        // println() add new line for each method
        System.out.println("What you know is a drop of Water, What you don't know is an Ocean");

        System.out.println(300); //unlike text, we don't put numbers inside double quotes
        System.out.println(20 + 30); //also perform mathematical calculations inside the println() method
        System.out.println(40 * 3 / 2);
    }
}
